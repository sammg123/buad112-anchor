/** Characters the font can't draw are dropped, so any text is safe to pass in. */
export const drawable = (text) =>
  String(text)
    .toUpperCase()
    .split('')
    .filter((ch) => ch in FONT)
    .join('');

/** A canvas of RGB pixels. */
export function createCanvas(width, height, [r, g, b]) {
  const pixels = Buffer.alloc(width * height * 3);
  for (let i = 0; i < width * height; i += 1) pixels.set([r, g, b], i * 3);
  const fillRect = (x0, y0, w, h, [cr, cg, cb]) => {
    for (let y = Math.max(0, y0); y < Math.min(height, y0 + h); y += 1) {
      for (let x = Math.max(0, x0); x < Math.min(width, x0 + w); x += 1) pixels.set([cr, cg, cb], (y * width + x) * 3);
    }
  };
  /** Text centered on `cy`, scaled so each font pixel is `scale` pixels. */
  const text = (str, cy, scale, color) => {
    const chars = drawable(str);
    const w = chars.length * 6 * scale - scale;
    const x0 = Math.round((width - w) / 2);
    const y0 = Math.round(cy - (7 * scale) / 2);
    [...chars].forEach((ch, i) => {
      FONT[ch].forEach((row, ry) => {
        [...row].forEach((cell, rx) => {
          if (cell === '#') fillRect(x0 + (i * 6 + rx) * scale, y0 + ry * scale, scale, scale, color);
        });
      });
    });
  };
  /** The biggest scale (up to `max`) at which the text fits the width with a margin. */
  const fitScale = (str, max, margin = 0.08) =>
    Math.max(1, Math.min(max, Math.floor((width * (1 - 2 * margin)) / (drawable(str).length * 6 || 1))));
  return { width, height, pixels, fillRect, text, fitScale };
}

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});

function crc32(buf) {
  let c = 0xffffffff;
  for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}

/** @param {ReturnType<typeof createCanvas>} canvas */
export function encodePng({ width, height, pixels }) {
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header.set([8, 2, 0, 0, 0], 8); // 8-bit RGB
  const raw = Buffer.alloc((width * 3 + 1) * height);
  for (let y = 0; y < height; y += 1) {
    raw[y * (width * 3 + 1)] = 0; // no filter
    pixels.copy(raw, y * (width * 3 + 1) + 1, y * width * 3, (y + 1) * width * 3);
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', header),
    chunk('IDAT', zlib.deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}
